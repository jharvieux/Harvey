// Fix outcome record + PR rendering. The PR is the unit of delivery, so its
// body is generated deterministically from the result. See
// docs/design/fix-implementation.md §5 (FixResult) and §7 (PR conventions).

import type { Finding } from "../findings.js";
import type { EscalationTier, FixPlan } from "./plan.js";
import type { CommandRun, VerificationEvidence } from "./verify.js";

export type FixOutcome = "pr-opened" | "recommend-only" | "aborted";

export interface FixResult {
  findingId: string;
  outcome: FixOutcome;
  plan: FixPlan;
  branch?: string; // harvey/fix/<finding-id>
  prUrl?: string; // draft PR
  evidence?: VerificationEvidence;
  tiersUsed: EscalationTier[]; // e.g. ["cheap","standard"] — cost/quality telemetry
  flagshipReview?: { verdict: "approved" | "rejected"; notes: string }; // Security category only
  downgradeOrAbortReason?: string;
  railEvents: string[]; // any rail checks that fired, even non-fatal ones
}

export function fixBranch(findingId: string): string {
  return `harvey/fix/${findingId}`;
}

export function prTitle(finding: Finding, summary: string): string {
  return `[${finding.id}] ${summary}`;
}

function clientCheckRow(c: CommandRun): string {
  if (c.skipped) return `| \`${c.command}\` | skipped — ${c.skipped} |`;
  const status = c.exitCode === 0 ? "exit 0" : `exit ${c.exitCode}`;
  return `| \`${c.command}\` | ${status}, ${Math.round(c.durationMs / 1000)}s |`;
}

// §7 PR body template, filled from the result. The rollback paragraph is
// mandatory and must be true — it's the enforcement mirror of rail 3.1(6).
export function renderPrBody(result: FixResult, finding: Finding, operator: string): string {
  const ev = result.evidence;
  const { plan } = result;
  const filesTouched = [...plan.blastRadius.files, ...plan.blastRadius.createdFiles].join(", ") || "(none recorded)";

  const preExisting = ev?.clientChecks
    .filter((c) => c.skipped === "pre-existing-failure-on-baseline")
    .map((c) => `\`${c.command}\``);

  const verificationTable = ev
    ? [
        "| Check | Result |",
        "|---|---|",
        `| Detector \`${ev.detectorBefore.detectorId}\` before | FIRED |`,
        `| Detector \`${ev.detectorAfter.detectorId}\` after | ${ev.detectorAfter.fired ? "STILL FIRING" : "clean"} |`,
        ...ev.clientChecks.map(clientCheckRow),
      ].join("\n")
    : "_No verification evidence (fix not implemented)._";

  return `## Fixes finding ${finding.id} — ${finding.title}
Severity: ${finding.severity} · Category: ${finding.category} · Confidence: ${finding.confidence}
Engagement commit: ${ev?.baselineCommit ?? "(unpinned)"}

### What was wrong
${finding.evidence.trim()} — ${finding.impact.trim()}

### What this PR does
${plan.approach}
Files touched: ${filesTouched}

### Verification
${verificationTable}
Pre-existing failures on baseline (not caused here): ${preExisting && preExisting.length ? preExisting.join(", ") : "none"}
New regression test: ${ev?.newTestAdded ?? "n/a"}

### Rollback
Close this PR / revert this single commit. No migrations, no dependency changes,
no config changes are included; reverting restores the exact prior behavior.

---
Generated by Harvey fix-implementation · reviewed by ${operator} before leaving draft.`;
}
