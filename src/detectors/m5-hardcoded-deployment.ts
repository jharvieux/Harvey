function normalizedPath(path: string): string {
  return path.replaceAll("\\", "/");
}

export function isM5HardcodedDeploymentSource(file: SourceInput): boolean {
  const path = normalizedPath(file.path);
  if (!SOURCE_EXTENSION.test(path) || NON_PRODUCT_FILE.test(path) || GENERATED_MARKER.test(file.text)) return false;
  return !path.split("/").slice(0, -1).some((segment) => NON_PRODUCT_SEGMENT.test(segment));
}

function propertyLabel(node: ts.StringLiteralLike): string | undefined {
  const parent = node.parent;
  if (!ts.isPropertyAssignment(parent) || parent.initializer !== node) return undefined;
  const name = parent.name;
  if (ts.isIdentifier(name) || ts.isStringLiteralLike(name) || ts.isNumericLiteral(name)) return name.text;
  return undefined;
}

function variableContainer(node: ts.Node): ts.VariableDeclaration | undefined {
  for (let current: ts.Node | undefined = node.parent; current; current = current.parent) {
    if (ts.isVariableDeclaration(current)) return current;
    if (ts.isStatement(current)) break;
  }
  return undefined;
}

function variableName(node: ts.VariableDeclaration | undefined): string | undefined {
  return node && ts.isIdentifier(node.name) ? node.name.text : undefined;
}

function callName(node: ts.CallExpression | ts.NewExpression, sf: ts.SourceFile): string {
  return node.expression.getText(sf).replace(/\s+/g, " ");
}

function supportedCall(node: ts.Node, sf: ts.SourceFile): ConsumerContext | undefined {
  for (let current: ts.Node | undefined = node.parent; current; current = current.parent) {
    if (ts.isCallExpression(current) || ts.isNewExpression(current)) {
      const name = callName(current, sf);
      if (ROUTE_CALL.test(name)) return { kind: "routing", node: current };
      if (REQUEST_CALL.test(name)) return { kind: "request", node: current };
      if (CLIENT_CALL.test(name) || (ts.isCallExpression(current) && /(?:^|\.)create$/i.test(name))) {
        return { kind: "client construction", node: current };
      }
      return undefined;
    }
    if (ts.isStatement(current)) return undefined;
  }
  return undefined;
}

function configContext(node: ts.Node, path: string, label: string | undefined): ConsumerContext | undefined {
  const declaration = variableContainer(node);
  const container = variableName(declaration);
  if (declaration && container && CONFIG_CONTAINER.test(container)) {
    return { kind: "configuration", label, node: declaration };
  }
  if (CONFIG_PATH.test(normalizedPath(path))) {
    const property = node.parent;
    return { kind: "configuration", label, node: ts.isPropertyAssignment(property) ? property : node };
  }
  return undefined;
}

function endpointUrl(value: string): URL | undefined {
  if (!/^https?:\/\//i.test(value)) return undefined;
  try {
    return new URL(value);
  } catch {
    return undefined;
  }
}

function isM1OwnedUrl(url: URL): boolean {
  if (url.username.length > 0 || url.password.length > 0) return true;
  return [...url.searchParams.keys()].some((key) => SECRET_QUERY_KEY.test(key));
}

function isDeploymentEndpoint(value: string): boolean {
  const url = endpointUrl(value);
  if (!url || isM1OwnedUrl(url)) return false;
  const host = url.hostname.toLowerCase();
  if (LOOPBACK_HOST.test(host) || EXAMPLE_HOST.test(host) || DEV_HOST.test(host)) return false;
  if (host.endsWith(".localhost") || host.endsWith(".local") || host.endsWith(".test")) return false;
  if (CANONICAL_PUBLIC_HOSTS.has(host)) return false;
  return ENVIRONMENT_HOST.test(host)
    || PRIVATE_NETWORK_HOST.test(host)
    || PROVIDER_TENANT_HOST.test(host)
    || AWS_GATEWAY_HOST.test(host)
    || /\.(?:corp|internal)$/i.test(host);
}

function isIdentifier(value: string, label: string | undefined): boolean {
  if (!label || !IDENTIFIER_LABEL.test(label) || SECRET_LABEL.test(label)) return false;
  if (PREFIXED_IDENTIFIER.test(value) || PATH_IDENTIFIER.test(value) || UUID.test(value)) return true;
  if (/account/i.test(label) && AWS_ACCOUNT.test(value)) return true;
  return /project/i.test(label)
    && PROJECT_SLUG.test(value)
    && (/\d/.test(value) || /(?:^|-)(?:prod|production|stage|staging)(?:-|$)/i.test(value));
}

function isClientSource(path: string, sf: ts.SourceFile): boolean {
  return leadingDirective(sf) === "use client" || CLIENT_SOURCE_PATH.test(normalizedPath(path));
}

function classifyContext(
  node: ts.StringLiteralLike,
  kind: DeploymentValueKind,
  path: string,
  sf: ts.SourceFile,
): ConsumerContext | undefined {
  const label = propertyLabel(node);
  if (label && SECRET_LABEL.test(label)) return undefined;
  const call = supportedCall(node, sf);
  if (kind === "identifier" && label && TENANT_SENSITIVE_LABEL.test(label)
    && (call?.kind === "request" || isClientSource(path, sf))) return undefined;

  if (call) {
    if (kind === "endpoint") return { ...call, label };
    if (label && IDENTIFIER_LABEL.test(label)) return { ...call, label };
  }

  const config = configContext(node, path, label);
  if (!config) return undefined;
  if (kind === "endpoint" && label && (STRONG_ENDPOINT_LABEL.test(label) || ENDPOINT_LABEL.test(label))) return config;
  if (kind === "identifier" && label && IDENTIFIER_LABEL.test(label)) return config;
  return undefined;
}

function compactConsumer(context: ConsumerContext, sf: ts.SourceFile): string {
  if (ts.isCallExpression(context.node)) return `${context.node.expression.getText(sf)}(…)`;
  if (ts.isNewExpression(context.node)) return `new ${context.node.expression.getText(sf)}(…)`;
  if (ts.isVariableDeclaration(context.node)) return `${context.node.name.getText(sf)} configuration`;
  if (ts.isPropertyAssignment(context.node)) return `${context.node.name.getText(sf)}: …`;
  return context.node.kind === ts.SyntaxKind.StringLiteral ? "literal consumer" : context.kind;
}

function safeValue(value: string, kind: DeploymentValueKind): string {
  if (kind === "endpoint") {
    const url = endpointUrl(value);
    if (!url) return value.slice(0, 100);
    return `${url.origin}${url.pathname}${url.search.length > 0 ? "?…" : ""}`.slice(0, 120);
  }
  if (value.length <= 9) return value;
  return `${value.slice(0, 4)}…${value.slice(-4)}`;
}

function upperSnake(value: string): string {
  return value
    .replace(/([a-z0-9])([A-Z])/g, "$1_$2")
    .replace(/[^a-zA-Z0-9]+/g, "_")
    .replace(/^_+|_+$/g, "")
    .toUpperCase();
}

function expectedSeam(context: ConsumerContext, value: string, kind: DeploymentValueKind): string {
  if (context.label) return upperSnake(context.label);
  if (kind === "endpoint") {
    const hostLabel = endpointUrl(value)?.hostname.split(".")[0];
    if (hostLabel) return `${upperSnake(hostLabel)}_BASE_URL`;
  }
  return kind === "endpoint" ? "SERVICE_BASE_URL" : "PROVIDER_RESOURCE_ID";
}

function findingFor(
  node: ts.StringLiteralLike,
  kind: DeploymentValueKind,
  context: ConsumerContext,
  path: string,
  sf: ts.SourceFile,
): Finding {
  const value = node.text;
  const displayed = safeValue(value, kind);
  const seam = expectedSeam(context, value, kind);
  const endpoint = kind === "endpoint";
  const idStem = endpoint ? "ENDPOINT" : "IDENTIFIER";
  const subject = endpoint ? "deployment endpoint" : "provider identifier";
  return mechanicalFinding({
    id: `M5-HARDCODED-${idStem}-${path.replace(/[^a-zA-Z0-9]+/g, "-")}-${node.getStart(sf)}`,
    title: `${path} — ${subject} is coupled to one environment`,
    severity: "Medium",
    category: "Maintainability",
    taxonomy: endpoint ? M5_HARDCODED_ENDPOINT_TAXONOMY : M5_HARDCODED_IDENTIFIER_TAXONOMY,
    location: loc(path, sf, node),
    evidence: `Literal value \`${displayed}\` is consumed by ${context.kind} node \`${compactConsumer(context, sf)}\`. Expected seam: validated env/config key \`${seam}\`.`,
    impact: "Deployments, tenant copies, or provider projects can silently keep talking to the environment embedded in source.",
    fix: `Move this value behind the validated runtime configuration seam \`${seam}\` and inject it into the same consumer.`,
    precisionTier: "review",
  });
}

interface M5HardcodedDeploymentOptions {
  enabled?: boolean;
}

/**
 * Source-only M5 classifier. It intentionally does not resolve dynamic values or consult provider
 * credentials/live state; the live registry owns applicability and NotAssessed accounting.
 */
export function detectM5HardcodedDeploymentFindings(
  files: readonly SourceInput[],
  options: M5HardcodedDeploymentOptions = {},
): Finding[] {
  if (options.enabled === false) return [];
  const findings: Finding[] = [];
  for (const file of files) {
    if (!isM5HardcodedDeploymentSource(file)) continue;
    const sf = parse(file.path, file.text);
    const visit = (node: ts.Node): void => {
      if (ts.isStringLiteralLike(node)) {
        const label = propertyLabel(node);
        if (!SECRET_LABEL.test(label ?? "")) {
          const kind = isDeploymentEndpoint(node.text)
            ? "endpoint"
            : isIdentifier(node.text, label) ? "identifier" : undefined;
          if (kind) {
            const context = classifyContext(node, kind, file.path, sf);
            if (context) findings.push(findingFor(node, kind, context, file.path, sf));
          }
        }
      }
      ts.forEachChild(node, visit);
    };
    visit(sf);
  }
  return findings;
}
