import ts from "typescript";
import type { Finding } from "../findings.js";
import { mechanicalFinding } from "../scan/common.js";
import { leadingDirective, loc, parse, type SourceInput } from "./common.js";

export const M5_HARDCODED_ENDPOINT_TAXONOMY = "M5 — Hardcoded deployment endpoint";
export const M5_HARDCODED_IDENTIFIER_TAXONOMY = "M5 — Hardcoded provider identifier";

const SOURCE_EXTENSION = /\.(?:[cm]?[jt]s|[jt]sx)$/i;
const NON_PRODUCT_SEGMENT = /^(?:\.next|__fixtures__|__tests__|build|coverage|dist|docs?|examples?|fixtures?|generated|mocks?|node_modules|out|samples?|test(?:s|data)?|vendor)$/i;
const NON_PRODUCT_FILE = /(?:^|\.)(?:generated|min|mock|spec|stories|test)\.[cm]?[jt]sx?$/i;
const GENERATED_MARKER = /(?:^|\n)\s*(?:\/\/|\/\*)\s*(?:@generated|generated by|code generated|do not edit\b)/i;

const ENDPOINT_LABEL = /^(?:api[_-]?url|base[_-]?url|destination|endpoint|host|origin|service[_-]?url|target|upstream|url|webhook[_-]?url)$/i;
const STRONG_ENDPOINT_LABEL = /^(?:api[_-]?url|base[_-]?url|destination|endpoint|service[_-]?url|upstream|webhook[_-]?url)$/i;
const IDENTIFIER_LABEL = /(?:^|[_-])(?:account|organisation|organization|org|project|provider|subscription|tenant|workspace)(?:[_-]?id)?$/i;
const TENANT_SENSITIVE_LABEL = /(?:^|[_-])(?:customer|member|organisation|organization|org|owner|tenant|user|workspace)(?:[_-]?id)?$/i;
const SECRET_LABEL = /(?:api[_-]?key|authorization|bearer|cookie|credential|jwt|password|private[_-]?key|secret|session|signature|signing|token)/i;
const CONFIG_CONTAINER = /(?:client|config|deployment|environment|options|provider|settings)/i;
const CONFIG_PATH = /(?:^|\/)(?:config|configuration|deploy|deployment|environment|infra|infrastructure|providers?|settings)(?:[/.]|$)/i;

const REQUEST_CALL = /(?:^|\.)(?:delete|fetch|get|head|patch|post|put|request)$/i;
const ROUTE_CALL = /(?:^|\.)(?:mount|proxy|redirect|rewrite|route|use)$/i;
const CLIENT_CALL = /(?:client|connector|gateway|provider|sdk|service|transport)/i;
const CLIENT_SOURCE_PATH = /(?:^|\/)(?:app|client|components?|pages?|ui)(?:\/|$)/i;

const CANONICAL_PUBLIC_HOSTS = new Set([
  "api.github.com",
  "api.openai.com",
  "api.stripe.com",
  "api.twilio.com",
  "api.sendgrid.com",
  "graph.microsoft.com",
  "login.microsoftonline.com",
  "s3.amazonaws.com",
  "storage.googleapis.com",
  "www.googleapis.com",
]);

const EXAMPLE_HOST = /(?:^|\.)(?:example\.(?:com|net|org)|example|invalid)$/i;
const LOOPBACK_HOST = /^(?:0\.0\.0\.0|127(?:\.\d{1,3}){3}|\[?::1\]?|localhost)$/i;
const DEV_HOST = /(?:^|[.-])(?:dev|development|fixture|local|mock|sandbox|test)(?:[.-]|$)/i;
const ENVIRONMENT_HOST = /(?:^|[.-])(?:prod|production|qa|preview|stage|staging)(?:[.-]|$)/i;
const PRIVATE_NETWORK_HOST = /^(?:10\.\d{1,3}(?:\.\d{1,3}){2}|172\.(?:1[6-9]|2\d|3[01])(?:\.\d{1,3}){2}|192\.168(?:\.\d{1,3}){2})$/;
const PROVIDER_TENANT_HOST = /(?:\.supabase\.co|\.firebaseio\.com|\.cloudfront\.net|\.azurewebsites\.net|\.vercel\.app|\.netlify\.app|\.run\.app)$/i;
const AWS_GATEWAY_HOST = /^[a-z0-9-]+\.execute-api\.[a-z0-9-]+\.amazonaws\.com$/i;
const SECRET_QUERY_KEY = /(?:api[_-]?key|authorization|credential|jwt|password|secret|signature|token)/i;

const PREFIXED_IDENTIFIER = /^(?:acc(?:ount)?|acct|org|prj|project|provider|sub(?:scription)?|tenant|workspace|ws)[_-][a-z0-9][a-z0-9_-]{5,}$/i;
const PATH_IDENTIFIER = /^(?:accounts?|organisations?|organizations?|projects?|providers?|subscriptions?|tenants?|workspaces?)\/[a-z0-9][a-z0-9._/-]{5,}$/i;
const UUID = /^[0-9a-f]{8}-[0-9a-f]{4}-[1-5][0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/i;
const AWS_ACCOUNT = /^\d{12}$/;
const PROJECT_SLUG = /^[a-z][a-z0-9-]{5,29}$/i;

type DeploymentValueKind = "endpoint" | "identifier";
type ConsumerKind = "client construction" | "configuration" | "request" | "routing";

interface ConsumerContext {
  kind: ConsumerKind;
  label?: string;
  node: ts.Node;
}

